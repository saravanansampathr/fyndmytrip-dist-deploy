// Regenerates backend/config/whitelabel_templates.php from the storefront's
// template catalog (storefront/js/templates.js), so the partner portal's
// template picker and the storefront always list the same 54 templates.
// Usage: node tools/storefront/sync-templates.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { TEMPLATES } from '../../storefront/js/templates.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const out = path.join(root, 'backend/config/whitelabel_templates.php');

// The compiled portal homepage (frontend/) still reads these three keys. The
// first 12 keep their original values; the rest cycle through the same 12
// combinations so every entry stays valid for that homepage too.
const LEGACY = [
  ['classic', 'cards', 'tabbed_card'], ['photo', 'showcase', 'card_deck'], ['minimal', 'compact', 'underline_tabs'],
  ['bold', 'compact', 'segmented_bar'], ['centered', 'showcase', 'dual_tone'], ['split', 'cards', 'sidebar_rail'],
  ['bold', 'cards', 'icon_tabs'], ['minimal', 'cards', 'floating_pill'], ['bold', 'magazine', 'wizard_steps'],
  ['split', 'compact', 'boxed_grid'], ['centered', 'magazine', 'stacked_vertical'], ['photo', 'magazine', 'compact_bar'],
];
const WORDS = {
  header: { bar: 'solid brand header', centered: 'centred logo header', split: 'pill-nav header', glass: 'frosted sticky header', rail: 'left sidebar navigation', ribbon: 'contact-ribbon header', stacked: 'two-row tabbed header' },
  hero: { 'tabs-card': 'tabbed search card', fullbleed: 'full-bleed photo search', split: 'split-panel search', line: 'sentence-style search', stack: 'stacked mobile-style search', icons: 'icon-grid search', wizard: 'step-by-step search', pill: 'floating capsule search', rail: 'side-rail search', magazine: 'editorial magazine search' },
  results: { list: 'list results', grid: 'card-grid results', table: 'fare-table results', timeline: 'timeline results', compact: 'compact one-line results', ticket: 'boarding-pass results', sidebar: 'results with filter sidebar', masonry: 'masonry results' },
  details: { panel: 'sticky price panel details', columns: 'three-column details', tabs: 'tabbed details', sheet: 'single-sheet details', banner: 'banner details' },
  travellers: { single: 'one-page traveller form', stepper: '3-step traveller form', accordion: 'accordion traveller form', cards: 'traveller cards', inline: 'compact traveller rows' },
  payment: { tabs: 'tabbed payment', radios: 'radio-list payment', tiles: 'tile payment', split: 'split summary payment', accordion: 'accordion payment', minimal: 'one-step payment' },
};
const q = (s) => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const rows = TEMPLATES.map((t, i) => {
  const [hero, flow, widget] = LEGACY[i % LEGACY.length];
  const L = t.layout;
  const parts = `${WORDS.header[L.header]}, ${WORDS.hero[L.hero]}, ${WORDS.results[L.results]}, ${WORDS.details[L.details]}, ${WORDS.travellers[L.travellers]} and ${WORDS.payment[L.payment]}`;
  const desc = `${t.audience}. ${parts[0].toUpperCase()}${parts.slice(1)}.`;
  const layout = Object.entries(L).map(([k, v]) => `${q(k)} => ${q(v)}`).join(', ');
  return `    ['id' => ${t.id}, 'name' => ${q(t.name)}, 'description' => ${q(desc)}, 'accent_color' => ${q(t.colors.primary)}, 'homepage_hero' => ${q(hero)}, 'homepage_flow' => ${q(flow)}, 'homepage_search_widget' => ${q(widget)}, 'storefront_layout' => [${layout}]],`;
});
const php = `<?php

/**
 * The white-label "choose a template" gallery: ${TEMPLATES.length} complete storefront
 * designs. GENERATED by tools/storefront/sync-templates.mjs from
 * storefront/js/templates.js. Edit that file, then rerun the script.
 *
 * Each entry:
 * - \`accent_color\`: one-click prefill for the "Brand theme" colour picker.
 * - \`storefront_layout\`: the page layouts the storefront (storefront/) uses
 *   for this template across the whole booking flow: header, home/search
 *   hero, results, details, traveller form, payment and footer.
 * - \`homepage_hero\` / \`homepage_flow\` / \`homepage_search_widget\`: read by
 *   the compiled portal homepage in frontend/ (lib/homeLayout.ts). Entries
 *   1-12 keep their original values; later entries reuse those 12 combos.
 *
 * Kept in config (not a DB table) since the catalog is platform-wide and
 * changes at deploy time.
 */
return [
${rows.join('\n')}
];
`;
fs.writeFileSync(out, php);
console.log(`wrote ${TEMPLATES.length} templates to ${path.relative(root, out)}`);
